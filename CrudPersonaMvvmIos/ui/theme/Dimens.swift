import Foundation

struct Dimens {
    
    static let extraSmall: CGFloat = 4.0
    static let small: CGFloat = 8.0
    static let mid: CGFloat = 12.0
    static let normal: CGFloat = 16.0
    static let large: CGFloat = 24.0
    static let extraLarge: CGFloat = 32.0
    static let xxxLarge: CGFloat = 40.0
    
}

extension CGFloat {
    static let paddingExtraSmall = Dimens.extraSmall
    static let paddingSmall = Dimens.small
    static let paddingMid = Dimens.mid
    static let paddingNormal = Dimens.normal
    static let paddingLarge = Dimens.large
    static let paddingExtraLarge = Dimens.extraLarge
    static let paddingXxxLarge = Dimens.xxxLarge
    
    
    
    // frame width
    static let frameSmall: CGFloat = 44
}
